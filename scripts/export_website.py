#!/usr/bin/env python3
"""Build and export the notebook into a personal website's systems/ntt-gpu topic."""

import argparse
from html import escape
import os
from pathlib import Path
import shutil

from build_docs import OUTPUT, build


MARKER = ".ntt-gpu-generated"
MARKER_TEXT = "Generated by ntt-gpu/scripts/export_website.py. Edit the source repository.\n"


def export(website_root):
    website_root = Path(website_root).resolve()
    if not (website_root / "index.html").is_file():
        raise ValueError("The website root must contain index.html")
    destination = website_root / "systems" / "ntt-gpu"
    if destination.resolve() != destination or not destination.is_relative_to(website_root):
        raise ValueError("Refusing to export through a symlink")
    if destination.exists():
        marker = destination / MARKER
        if not marker.is_file() or marker.read_text() != MARKER_TEXT:
            raise ValueError("Destination contains unmanaged files; refusing to overwrite it")
    build()
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(OUTPUT, destination)
    for page in destination.rglob("*.html"):
        home = Path(os.path.relpath(website_root / "index.html", page.parent)).as_posix()
        return_link = (
            '<a class="site-personal-home" style="margin:0 0 14px" href="'
            + escape(home, quote=True) + '#code">← Systems from Scratch</a>'
        )
        page.write_text(page.read_text().replace(
            '<div class="site-sidebar-bottom">',
            '<div class="site-sidebar-bottom">' + return_link,
            1,
        ))
    (destination / MARKER).write_text(MARKER_TEXT)
    print(f"Exported notebook to: {destination}")
    print(f"HTML entry page: {destination / 'index.html'}")
    print("Serve the website root; open /#code or /systems/ntt-gpu/index.html.")
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--website-root", required=True, type=Path)
    args = parser.parse_args()
    try:
        export(args.website_root)
    except (OSError, ValueError) as error:
        raise SystemExit(f"Website export failed: {error}") from error


if __name__ == "__main__":
    main()
